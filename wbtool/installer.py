"""Install/uninstall helpers: Startup shortcut + Desktop links."""
from __future__ import annotations

import os
from pathlib import Path

from .config import PROJECT_DIR
from .shortcuts import (
    ensure_directory_link,
    ensure_file_link,
    link_kind,
    remove_startup_shortcut,
    set_startup_enabled,
    startup_shortcut_path,
    startup_state,
)
from .win32 import desktop_dir

SCRIPT_PATH = PROJECT_DIR / "my_devices.py"
LAUNCHER_PATH = PROJECT_DIR / "电量托盘启动器.pyw"
DESKTOP_DIR_LINK = "电量托盘项目"
DESKTOP_FILE_LINK = "电量托盘.pyw"


def _write_launcher() -> Path:
    """Generate the tiny file-link target.

    The Desktop file entry may have to be a hardlink (when symlink privilege is
    unavailable), and a hardlink cannot discover the project directory.  This
    launcher therefore contains the absolute project path at install time; it
    is not a copy of the application code.
    """
    text = (
        "# -*- coding: utf-8 -*-\n"
        "# Generated by my_devices.py --install.  Desktop file links target this file.\n"
        "import os\n"
        "import runpy\n"
        "import sys\n"
        "sys.dont_write_bytecode = True\n"
        f"PROJECT = {str(PROJECT_DIR)!r}\n"
        "os.chdir(PROJECT)\n"
        "SCRIPT = os.path.join(PROJECT, 'my_devices.py')\n"
        "sys.argv = [SCRIPT, '--tray']\n"
        "runpy.run_path(SCRIPT, run_name='__main__')\n"
    )
    # Deliberately write in place instead of os.replace: the Desktop entry is a
    # hardlink to this inode and must stay linked after an upgrade.
    with open(LAUNCHER_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return LAUNCHER_PATH


def desktop_paths() -> tuple[Path, Path]:
    desktop = Path(desktop_dir())
    return desktop / DESKTOP_DIR_LINK, desktop / DESKTOP_FILE_LINK


def install(startup_enabled: bool = True) -> dict:
    """Create (or repair) the Startup shortcut and both Desktop links."""
    launcher = _write_launcher()
    startup = {"created": False, "error": ""}
    try:
        if startup_enabled:
            state = set_startup_enabled(True, str(PROJECT_DIR), str(SCRIPT_PATH))
        else:
            state = set_startup_enabled(False, str(PROJECT_DIR), str(SCRIPT_PATH))
        startup = {"created": True, "error": "", "state": state}
    except Exception as exc:
        startup = {"created": False, "error": str(exc)}

    dir_link, file_link = desktop_paths()
    links = {}
    try:
        kind = ensure_directory_link(dir_link, PROJECT_DIR)
        links["directory"] = {"ok": True, "path": str(dir_link), "kind": kind}
    except Exception as exc:
        links["directory"] = {"ok": False, "path": str(dir_link), "error": str(exc)}
    try:
        kind = ensure_file_link(file_link, launcher)
        links["file"] = {"ok": True, "path": str(file_link), "kind": kind}
    except Exception as exc:
        links["file"] = {"ok": False, "path": str(file_link), "error": str(exc)}

    return {
        "project": str(PROJECT_DIR),
        "script": str(SCRIPT_PATH),
        "launcher": str(launcher),
        "startup": startup,
        "startup_state": startup_state(),
        "links": links,
    }


def uninstall(remove_links: bool = True) -> dict:
    remove_startup_shortcut()
    removed = []
    errors = []
    if remove_links:
        dir_link, file_link = desktop_paths()
        for path in (dir_link, file_link):
            try:
                if path.is_symlink() or path.is_file():
                    path.unlink()
                    removed.append(str(path))
                elif path.is_dir():
                    # Junction: unlink() removes the reparse point without
                    # touching the project directory.  rmdir on a junction with
                    # Python 3.15 removes the link itself.
                    os.rmdir(path)
                    removed.append(str(path))
            except Exception as exc:
                errors.append(f"{path}: {exc}")
    return {"removed": removed, "errors": errors}


def current_state() -> dict:
    dir_link, file_link = desktop_paths()
    return {
        "startup": startup_state(),
        "desktop_directory": {
            "path": str(dir_link),
            "exists": dir_link.exists(),
            "kind": link_kind(dir_link),
        },
        "desktop_file": {
            "path": str(file_link),
            "exists": file_link.exists(),
            "kind": link_kind(file_link),
        },
        "launcher_exists": LAUNCHER_PATH.is_file(),
    }


def describe_install(result: dict) -> str:
    lines = []
    startup = result.get("startup", {})
    if startup.get("created"):
        lines.append(f"启动项：{startup_shortcut_path()}")
    else:
        lines.append(f"启动项创建失败：{startup.get('error', '未知错误')}")
    for label, item in result.get("links", {}).items():
        if item.get("ok"):
            lines.append(f"桌面{'目录' if label == 'directory' else '文件'}链接：{item['path']}（{item['kind']}）")
        else:
            lines.append(f"桌面链接失败：{item.get('path')}：{item.get('error')}")
    return "\n".join(lines)
